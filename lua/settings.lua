-- lua/settings.lua
-- Опции Neovim (перенос set-команд из .vimrc)

local o = vim.opt
local g = vim.g

---------------------------------------------------------------------------
-- Общая совместимость / кодировка
---------------------------------------------------------------------------
-- nocompatible в Neovim не нужен, но ради единообразия
o.compatible = false

-- Подавлять звуковые ошибки
o.visualbell = true
-- в nvim t_vb можно не трогать, но очистим на всякий случай
vim.cmd([[set t_vb=]])

-- UTF-8 как стандартная кодировка
o.encoding = "utf-8"

---------------------------------------------------------------------------
-- Курсор / мышь / файлы подкачки
---------------------------------------------------------------------------
-- Включить мышь (все режимы)
o.mouse = "a"

-- Визуальные отступы сверху/снизу от курсора
o.scrolloff = 5

-- Подсветка строки с курсором
o.cursorline = true

-- Ширина строки
o.textwidth = 120

-- Файлы подкачки
vim.opt.directory:prepend(vim.env.HOME .. "/.local/share/nvim/swap//")

-- updatetime / autoread
o.updatetime = 250
o.autoread = true
vim.api.nvim_create_autocmd({ "FocusGained", "BufEnter", "CursorHold", "CursorHoldI" }, {
  group = vim.api.nvim_create_augroup("settings_checktime", { clear = true }),
  command = "checktime",
})

---------------------------------------------------------------------------
-- Тема
---------------------------------------------------------------------------
-- colorscheme industry больше не поставляется с vim/neovim по умолчанию.
-- Установи `industry` или `vim-industry` через lazy.nvim и раскомментируй:
-- vim.cmd("colorscheme industry")

---------------------------------------------------------------------------
-- Отступы
---------------------------------------------------------------------------
o.tabstop = 2
o.shiftwidth = 2
o.smarttab = true
o.expandtab = true
o.smartindent = true

---------------------------------------------------------------------------
-- Поиск
---------------------------------------------------------------------------
o.ignorecase = true
o.smartcase = true
o.incsearch = true

---------------------------------------------------------------------------
-- Буферы / вкладки
---------------------------------------------------------------------------
o.hidden = true

---------------------------------------------------------------------------
-- Номера строк
---------------------------------------------------------------------------
o.number = true

---------------------------------------------------------------------------
-- Мап-лидер / таймауты
---------------------------------------------------------------------------
g.mapleader = ","
o.timeout = true
o.timeoutlen = 1500

---------------------------------------------------------------------------
-- Русская раскладка: langmap
---------------------------------------------------------------------------
o.langmap = "ёйцукенгшщзхъфывапролджэячсмитьбюЁЙЦУКЕНГШЩЗХЪФЫВАПРОЛДЖЭЯЧСМИТЬБЮ;`qwertyuiop[]asdfghjkl\\;'zxcvbnm\\,.~QWERTYUIOP{}ASDFGHJKL:\\\"ZXCVBNM<>"

---------------------------------------------------------------------------
-- Глобальный буфер обмена
---------------------------------------------------------------------------
-- Используем системный буфер (+ и *) напрямую, без xclip.
-- На Linux Wayland/X11, macOS и Windows nvim умеет это нативно.
o.clipboard = "unnamedplus"

---------------------------------------------------------------------------
-- Автосохранение при выходе из буфера
---------------------------------------------------------------------------
vim.api.nvim_create_autocmd("BufLeave", {
  group = vim.api.nvim_create_augroup("auto_save", { clear = true }),
  command = "silent! wa",
})

---------------------------------------------------------------------------
-- Вставка из глобального буфера (внешняя вставка / InsertEnter)
---------------------------------------------------------------------------
-- В .vimrc были функции PasteGlobal/InsertClipboardGlobalVisual, использующие
-- xclip. Они перенесены в keymaps.lua как обычные "+p / "+y регистровые
-- операции. Здесь дополнительно делаем отключение autoindent/paste при
-- InsertEnter не требуется, так как Neovim работает с буфером напрямую.

---------------------------------------------------------------------------
-- Авто-обновление локальной директории по открытому файлу
---------------------------------------------------------------------------
vim.api.nvim_create_autocmd("BufEnter", {
  group = vim.api.nvim_create_augroup("settings_lcd", { clear = true }),
  callback = function()
    vim.cmd("silent! lcd %:p:h")
  end,
})

return {}